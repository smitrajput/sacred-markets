/**
 * Generates src/contracts/abis.ts from the compiled Foundry artifacts (run `forge build` first).
 * The app, the API and the keeper all import these actual ABIs; nothing is retyped by hand.
 *   bun scripts/gen-abis.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const targets: Array<[string, string]> = [
  ['MarginVault', 'marginVaultAbi'],
  ['TradeEngine', 'tradeEngineAbi'],
  ['DemoPriceGuard', 'demoPriceGuardAbi'],
]
let out = '// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit by hand.\n\n'
for (const [name, ident] of targets) {
  const art = JSON.parse(readFileSync(join(ROOT, 'contracts', 'out', `${name}.sol`, `${name}.json`), 'utf8')) as { abi: unknown[] }
  out += `export const ${ident} = ${JSON.stringify(art.abi)} as const\n\n`
}
writeFileSync(join(ROOT, 'src', 'contracts', 'abis.ts'), out)
console.log('wrote src/contracts/abis.ts')
